#!/usr/bin/env python3
"""Execute reviewed P040 local source-separation task plan. Writes ONLY to output dirs.

This intentionally does not classify stem quality as verified: automated technical checks
are not a substitute for human auditory listening on real singing.
"""
from __future__ import annotations
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import time
from p040_smart_import import probe,sha256


def run_jobs(task_json: Path, *, execute:bool=False, max_jobs:int|None=None, separator:str='audio-separator') -> dict:
    data=json.loads(task_json.read_text(encoding='utf-8'))
    tasks=data.get('tasks',[])
    results=[]
    if execute and not shutil.which(separator):raise RuntimeError('audio-separator is not installed. Run this on native Mac mini after preflight.')
    for task in tasks[:max_jobs]:
        command=list(task['command'])
        if command[0]!='audio-separator':raise ValueError('unexpected task command')
        # Guard command provenance: protect owner's input directory even when
        # someone edits the JSON task file after scanning.
        if len(command)<7 or command[1]!=task['input'] or '--output_dir' not in command:
            raise ValueError('unexpected extraction command structure')
        # Task files must have come from local scan. Never permit output path
        # rewriting to the input path, and never replace existing outputs.
        input_path=Path(task['input'])
        output_path=Path(task['expectedOutput'])
        dest_arg=Path(command[command.index('--output_dir')+1]).resolve()
        if dest_arg != output_path.parent.resolve():raise ValueError('output_dir does not match expected output parent')
        if not input_path.is_file():raise FileNotFoundError(f'missing input: {input_path}')
        if output_path.exists():
            results.append({'songId':task['songId'],'status':'skipped-output-exists','output':str(output_path)})
            continue
        if not execute:
            results.append({'songId':task['songId'],'status':'dry-run','command':command})
            continue
        # All output paths are generated by the planner; reject accidental same-parent write.
        if output_path.parent.resolve() == input_path.parent.resolve():raise ValueError('output cannot equal source folder')
        output_path.parent.mkdir(parents=True,exist_ok=True)
        command[0]=separator
        start=time.monotonic()
        try:
            done=subprocess.run(command,check=True,capture_output=True,text=True,timeout=2700)
            if not output_path.exists():
                raise RuntimeError('Separator exited but expected accompaniment is missing; check installed model naming convention')
            original=probe(input_path);accomp=probe(output_path)
            a=original['durationMs'];b=accomp['durationMs']
            if not a or not b or abs(a-b)>max(1000, int(a*0.015)):
                raise RuntimeError(f'Audio duration mismatch: original={a}, accompaniment={b}')
            results.append({'songId':task['songId'],'status':'ready-for-listening-QA',
                            'output':str(output_path),'sha256':sha256(output_path),
                            'durationMs':b,'elapsedSec':round(time.monotonic()-start,2)})
        except Exception as e:
            # Preserve any intermediate artifacts; never delete owner recordings.
            results.append({'songId':task['songId'],'status':'failed','error':str(e),
                            'elapsedSec':round(time.monotonic()-start,2)})
    return {'mode':'execute' if execute else 'dry-run','results':results}


def main(argv=None):
    p=argparse.ArgumentParser(description='Execute P040 accompaniment extraction; requires explicit --execute')
    p.add_argument('tasks',type=Path)
    p.add_argument('--execute',action='store_true')
    p.add_argument('--max-jobs',type=int)
    p.add_argument('--separator-bin',default='audio-separator')
    p.add_argument('--result',type=Path,default=Path('separation-results.json'))
    args=p.parse_args(argv)
    if args.max_jobs is not None and args.max_jobs < 1:p.error('--max-jobs must be positive')
    result=run_jobs(args.tasks,execute=args.execute,max_jobs=args.max_jobs,separator=args.separator_bin)
    args.result.parent.mkdir(parents=True,exist_ok=True)
    args.result.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({ 'result':str(args.result),'statuses':[x['status'] for x in result['results']] },ensure_ascii=False))

if __name__=='__main__':main()
